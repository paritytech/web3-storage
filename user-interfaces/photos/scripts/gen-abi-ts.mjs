// Generate the tracked, viem-typed `src/contract/photos-abi.ts` from the
// compiled `Photos.json` that `extract.mjs` produces. Run by `build:contract`;
// the committed output lets the UI and CI work without the solc+resolc toolchain.
//   node gen-abi-ts.mjs <Photos.json> <photos-abi.ts>

import { readFileSync, writeFileSync } from "node:fs";

const [, , artifactPath, outPath] = process.argv;
if (!artifactPath || !outPath) {
  console.error("usage: gen-abi-ts.mjs <Photos.json> <photos-abi.ts>");
  process.exit(1);
}

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));
if (!Array.isArray(abi)) {
  console.error(`${artifactPath} has no \`abi\` array`);
  process.exit(1);
}

// A JSON literal is already valid TS (double-quoted keys/strings), so emit it
// verbatim — no quote rewriting that could corrupt an escaped character.
const literal = JSON.stringify(abi, null, 2);

const out = `// SPDX-License-Identifier: GPL-3.0-only
//
// GENERATED by \`pnpm build:contract\` (resolc -> extract.mjs -> gen-abi-ts.mjs)
// from \`contracts/Photos.sol\`. DO NOT EDIT BY HAND — re-run the build instead.
// Committed because the UI imports it and the source \`Photos.json\` is git-ignored.

import type { Abi } from 'viem'

export const PHOTOS_ABI = ${literal} as const satisfies Abi
`;

writeFileSync(outPath, out);
